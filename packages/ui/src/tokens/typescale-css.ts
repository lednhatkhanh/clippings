import { TYPESCALE_NAMES, TYPESCALE_ROLES, type TypescaleName } from "./typescale";

const rem = (px: number) => `${px / 16}rem`;
const prop = (name: TypescaleName, part: string) => `--md-sys-typescale-${name}-${part}`;

/**
 * `typescale.css`: the role properties, their medium/compact overrides, and one `typescale-*`
 * utility per role. Utilities use longhands on purpose: the `font` shorthand would reset
 * `font-variant-*` and `font-optical-sizing` inherited from a parent.
 */
export const renderTypescaleCss = (): string => {
  const base: string[] = [];
  const medium: string[] = [];
  const compact: string[] = [];
  const utilities: string[] = [];

  for (const name of TYPESCALE_NAMES) {
    const role = TYPESCALE_ROLES[name];
    const family = role.family === "brand" ? "--md-ref-typeface-brand" : "--md-ref-typeface-plain";
    base.push(
      `  ${prop(name, "font")}: var(${family});`,
      `  ${prop(name, "size")}: ${rem(role.size)};`,
      `  ${prop(name, "line-height")}: ${rem(role.lineHeight)};`,
      `  ${prop(name, "tracking")}: ${rem(role.tracking)};`,
      `  ${prop(name, "weight")}: ${role.weight};`,
    );
    if (role.medium) {
      medium.push(
        `    ${prop(name, "size")}: ${rem(role.medium.size)};`,
        `    ${prop(name, "line-height")}: ${rem(role.medium.lineHeight)};`,
      );
    }
    if (role.compact) {
      compact.push(
        `  ${prop(name, "size")}: ${rem(role.compact.size)};`,
        `  ${prop(name, "line-height")}: ${rem(role.compact.lineHeight)};`,
      );
      if (role.compact.weight) compact.push(`  ${prop(name, "weight")}: ${role.compact.weight};`);
    }
    utilities.push(
      `@utility typescale-${name} {`,
      `  font-family: var(${prop(name, "font")});`,
      `  font-size: var(${prop(name, "size")});`,
      `  line-height: var(${prop(name, "line-height")});`,
      `  letter-spacing: var(${prop(name, "tracking")});`,
      `  font-weight: var(${prop(name, "weight")});`,
      "}",
      "",
    );
  }

  return [
    "/* Generated by packages/ui/scripts/generate-theme.ts. Do not edit. */",
    ":root {",
    ...base,
    "}",
    "",
    "@media (min-width: 37.5rem) {",
    "  :root {",
    ...medium,
    "  }",
    "}",
    "",
    ':root[data-density="compact"] {',
    ...compact,
    "}",
    "",
    ...utilities,
  ].join("\n");
};
