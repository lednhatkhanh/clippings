/** The page a navigation falls back to when the network is down. */
export const OFFLINE_PATH = "/offline";

/** What the update toast posts to the waiting worker to make it take over. */
export const SKIP_WAITING = "SKIP_WAITING";

/**
 * The service worker's source, for `/sw.js`. Plain JavaScript in a string, so there is no build
 * step. It stores no user data: only content-hashed static assets, icons, the manifest and the
 * static offline page, in one cache per deployment. Pages, RSC payloads, the API, auth and MCP go
 * to the network untouched. A new version waits until the page posts `SKIP_WAITING`. Hand-written
 * rather than Serwist or Workbox: docs/adr/0003-hand-written-service-worker.md.
 */
export function serviceWorkerSource(version: string): string {
  return `// Clippings service worker. Generated by app/sw.js/route.ts.
const CACHE = ${JSON.stringify(`clippings-${version}`)};
const OFFLINE = ${JSON.stringify(OFFLINE_PATH)};

// Never intercepted, past a navigation's preloaded response: the API (auth callbacks included),
// sign-in and OAuth consent, discovery documents and the MCP endpoint.
const PASS_THROUGH = ["/api/", "/sign-in", "/oauth", "/.well-known/", "/mcp"];

// Content-hashed build output (scripts, styles, fonts), the app icons and the manifest.
const STATIC = ["/_next/static/", "/icon", "/apple-icon", "/favicon", "/manifest.webmanifest"];

const startsWithAny = (path, prefixes) => prefixes.some((prefix) => path.startsWith(prefix));

self.addEventListener("install", (event) => {
  // Precache the offline page and the assets it loads, so it renders with no network at all.
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      const response = await fetch(OFFLINE, { cache: "reload" });
      if (!response.ok) throw new Error("Couldn't fetch " + OFFLINE);
      const html = await response.clone().text();
      const assets = new Set(html.match(/\\/_next\\/static\\/[^"'\\s)\\\\]+/g) ?? []);
      await cache.put(OFFLINE, response);
      // One missing asset shouldn't stop the worker installing.
      await Promise.allSettled([...assets].map((asset) => cache.add(asset)));
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys.filter((key) => key.startsWith("clippings-") && key !== CACHE).map((key) => caches.delete(key)),
      );
      // Navigations are network-only, so start their request while the worker boots instead of
      // after it: a page load never waits on the worker.
      await self.registration.navigationPreload?.enable();
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data?.type === ${JSON.stringify(SKIP_WAITING)}) self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    // Network-only: a page is per-user, so it is never stored. Offline, show the offline page.
    // Every navigation answers with its preloaded response, the pass-through paths too: one left
    // to the browser may be requested a second time, and an OAuth callback's code works once.
    event.respondWith(
      (async () => {
        try {
          return (await event.preloadResponse) ?? (await fetch(request));
        } catch {
          return (await caches.match(OFFLINE, { cacheName: CACHE })) ?? Response.error();
        }
      })(),
    );
    return;
  }

  if (startsWithAny(url.pathname, PASS_THROUGH)) return;
  // RSC payloads are per-user: leave them, and prefetches, to the network.
  if (request.headers.has("RSC") || url.searchParams.has("_rsc")) return;

  if (startsWithAny(url.pathname, STATIC)) {
    event.respondWith(
      (async () => {
        const cache = await caches.open(CACHE);
        const cached = await cache.match(request);
        if (cached) return cached;
        const response = await fetch(request);
        if (response.ok) event.waitUntil(cache.put(request, response.clone()));
        return response;
      })(),
    );
  }
});
`;
}
